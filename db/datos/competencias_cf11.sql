-- (una sola vez: volver a correr el script no cambia nada ni repite el registro)
INSERT INTO auditoria (id_usuario, accion, entidad, detalle)
SELECT NULL, 'carga_masiva_competencias', 'competencia',
       jsonb_build_object('origen', 'db/datos/competencias_cf11.sql', 'competencias', 7, 'raps', 27)
WHERE NOT EXISTS (
  SELECT 1 FROM auditoria
  WHERE accion = 'carga_masiva_competencias' AND detalle->>'origen' = 'db/datos/competencias_cf11.sql'
);

COMMIT;
